# Шаблоны сообщений продавцу в VK.
VK_MESSAGE_TEMPLATE = "[Ответ на вопрос {step}] Сообщение от {link} ({text})"
VK_CALL_TEMPLATE = "Вас вызывают ({link})"


def vk_message(link: str, text: str, step: int) -> str:
    """Уведомление продавцу: текст, который прислал покупатель."""
    return VK_MESSAGE_TEMPLATE.format(step=step, link=link, text=text)


def vk_call(link: str) -> str:
    """Уведомление продавцу: покупатель позвал его."""
    return VK_CALL_TEMPLATE.format(link=link)
